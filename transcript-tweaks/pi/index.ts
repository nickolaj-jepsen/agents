/** One span in the theme: a span with no role keeps the terminal's own colour. */
function paintSpan(theme, s) {
	let out = s.role ? theme.fg(ROLE[s.role], s.text) : s.text;
	if (s.bold) out = theme.bold(out);
	if (s.italic) out = theme.italic(out);
	if (s.underline) out = theme.underline(out);
	if (s.inverse) out = theme.inverse(out);
	return out;
}
const paintSpans = (theme, spans) => spans.map((s) => paintSpan(theme, s)).join("");
function markdownTheme(theme) {
	const color = (role) => (text) => theme.fg(role, text);
	return {
		heading: color("mdHeading"),
		link: color("mdLink"),
		linkUrl: color("mdLinkUrl"),
		code: color("mdCode"),
		codeBlock: color("mdCodeBlock"),
		codeBlockBorder: color("mdCodeBlockBorder"),
		quote: color("mdQuote"),
		quoteBorder: color("mdQuoteBorder"),
		hr: color("mdHr"),
		listBullet: color("mdListBullet"),
		bold: (text) => theme.bold(text),
		italic: (text) => theme.italic(text),
		underline: (text) => theme.underline(text),
		strikethrough: (text) => theme.strikethrough(text),
		highlightCode(code, lang) {
			try {
				return getMarkdownTheme().highlightCode?.(code, lang) ?? code.split("\n").map(color("mdCodeBlock"));
			} catch {
				return code.split("\n").map(color("mdCodeBlock"));
			}
		}
	};
}
/**
* Block Markdown by pi's own renderer, at most `max` lines, the last of a cut one ending in
* `…`. A line in a default style ends with it still open and pi pads every line to the
* terminal's edge, so each is closed here.
*/
function markdownLines(theme, text, width, style, max = 1e400) {
	const lines = new Markdown(text, 0, 0, markdownTheme(theme), style).render(width).map((row) => row.trimEnd());
	if (lines.length > max) {
		lines.length = Math.max(0, max);
		const last = lines.pop();
		if (last !== void 0) lines.push(truncateToWidth(last, Math.max(0, width - 1), "") + (style?.color ?? String)("…"));
	}
	return lines.map((row) => `${row}\x1b[0m`);
}
const slotRows = (theme, slot) => markdownLines(theme, slot.text, slot.width, slot.isDim ? { color: (text) => theme.fg("dim", text) } : void 0, slot.max).map((row) => " ".repeat(slot.indent) + row);
/**
* @param width pi's own measure has the last word: a line it counts wider is cut, since pi
* refuses a render with one that does not fit.
*/
function paintLines(theme, lines, width, { fill = false } = {}) {
	const out = {
		lines: [],
		fields: [],
		hits: [],
		cells: []
	};
	const push = (text, hit, cells) => {
		const fit = visibleWidth(text) > width ? truncateToWidth(text, width, "") : text;
		out.lines.push(fill ? fit + " ".repeat(Math.max(0, width - visibleWidth(fit))) : fit);
		out.hits.push(hit);
		out.cells.push(cells);
	};
	for (const l of lines) {
		if (l.slot?.kind === "input") {
			const lead = paintSpans(theme, l.slot.lead);
			const tail = paintSpans(theme, l.slot.tail ?? []);
			const hang = l.slot.hang ? paintSpans(theme, l.slot.hang) : " ".repeat(visibleWidth(lead));
			const rows = l.slot.rows ?? 1;
			out.fields.push({
				row: out.lines.length,
				rows,
				lead,
				hang,
				tail,
				width: l.slot.width
			});
			push(lead + " ".repeat(l.slot.width) + tail, void 0, []);
			const under = hang + " ".repeat(l.slot.width) + tail;
			for (let row = 1; row < rows; row++) push(under, void 0, []);
			continue;
		}
		if (l.slot?.kind === "markdown") {
			for (const row of slotRows(theme, l.slot)) push(row, l.hit, []);
			continue;
		}
		const cells = [];
		let at = 0;
		let text = "";
		for (const s of l.spans) {
			const end = at + visibleWidth(s.text);
			const last = cells[cells.length - 1];
			if (s.hit !== void 0) {
				if (last && last.hit === s.hit && last.end === at) last.end = end;
				else cells.push({
					start: at,
					end,
					hit: s.hit
				});
			}
			text += paintSpan(theme, s);
			at = end;
		}
		if (l.hit !== void 0 && !cells.length) {
			const drawn = visibleWidth(l.spans.map((s) => s.text).join("").trimEnd());
			if (drawn > 0) cells.push({
				start: 0,
				end: drawn,
				hit: l.hit
			});
		}
		push(text, l.hit, cells);
	}
	return out;
}
/** Lines painted, for where only the rows are wanted. */
const draw = (theme, lines, width) => paintLines(theme, lines, width).lines;

// src/lib/summary.ts
/**
* What a folded tool result says, as the kit's styled spans: the model the pi renderer paints.
*
* A folded result is one line: a success check, the facts about the work (duration, size), and,
* for a shell command, the line it ended on. Everything else keeps pi's own rendering; `folds`
* says which calls this one answers.
*/
/** Tools whose result body is the payload, not a report about work: the diff, the question, the queue. */
const KEEP_BODY = /* @__PURE__ */ new Set([
	"edit",
	"write",
	"ask_user_question",
	"docfix"
]);
const QUOTE_LAST_LINE = /* @__PURE__ */ new Set(["bash"]);
/** Whether a headless body stays pi's: its result is the thing itself rather than a report. */
const keepsBody = (toolName) => KEEP_BODY.has(toolName);
/** A duration as the folded line says it: milliseconds under a second, one decimal above. */
const seconds = (ms) => ms < 1e3 ? `${Math.round(ms)}ms` : `${Math.round(ms / 100) / 10}s`;
/**
* Whether a result is folded to the summary line. Expansion, streaming output, failures and
* results that are pictures keep pi's own rendering; so does a tool whose body is the payload.
*/
const folds = (toolName, { expanded, isPartial, isError, hasImage }) => !KEEP_BODY.has(toolName) && !expanded && !isPartial && !isError && !hasImage;
/** The last line of a shell result, when that is the line worth reading. */
const quotedLine = (toolName, body) => {
	if (!QUOTE_LAST_LINE.has(toolName)) return void 0;
	const last = body.trimEnd().split("\n").at(-1)?.trim();
	return last ? last : void 0;
};
/**
* The folded result as one row's spans: `✓ 1.3s · 12 lines · exit 0`, with a shell command's
* last line in the text role. The success meaning's own glyph opens the row, so it matches the
* mark the kit draws elsewhere on the terminal.
*/
function summarySpans({ toolName, body, durationMs }) {
	const text = body.trimEnd();
	const facts = [];
	if (durationMs !== void 0) facts.push(span(seconds(durationMs), { role: "dim" }));
	if (text !== "") {
		const lines = text.split("\n").length;
		facts.push(span(`${lines} ${lines === 1 ? "line" : "lines"}`, { role: "dim" }));
	}
	const spans = [meaningSpan("state:success")];
	facts.forEach((fact, at) => {
		spans.push(span(at === 0 ? " " : " · ", { role: "dim" }));
		spans.push(fact);
	});
	const last = quotedLine(toolName, text);
	if (last) spans.push(span(" · ", { role: "dim" }), span(last, { role: "text" }));
	return spans;
}

// src/pi/condense.ts
/**
* Draws a collapsed tool result as one line: status, duration, size and, for a
* shell command, the line it ended on. Pi's own collapsed form previews five to
* twenty lines per result, which is where most of the transcript's height goes.
*
* The row's words are the summary model's (`../lib/summary.ts`); this file only
* paints them through the kit at the room the transcript gives.
*
* Everything else delegates through `next()`: expansion, streaming output,
* failures and the tools whose result body is the payload rather than a report
* about work done.
*/
const showsImage = (result) => (result.content ?? []).some((block) => block.type === "image");
/** One line whatever it says: a wrapped summary would defeat the point. */
const oneLine = (theme, spans) => ({
	render: (width) => {
		const room = Math.max(1, width);
		return draw(theme, [line(truncateSpans(spans, room))], room);
	},
	invalidate: () => {}
});
function condense_default(pi) {
	pi.registerToolRenderer((toolName, next) => {
		const base = next();
		const delegate = base?.renderResult;
		if (!delegate || keepsBody(toolName)) return base;
		return {
			...base,
			renderResult: (result, options, theme, context) => {
				if (!folds(toolName, {
					expanded: options.expanded,
					isPartial: options.isPartial,
					isError: context.isError,
					hasImage: showsImage(result)
				})) return delegate(result, options, theme, context);
				return oneLine(theme, summarySpans({
					toolName,
					body: contentText(result.content ?? []).trimEnd(),
					durationMs: context.durationMs
				}));
			}
		};
	});
}

// src/pi/gutter.ts
const GUTTER = "▌";
function gutter_default(pi) {
	pi.registerMarkdownTransformer((markdown, context) => {
		if (context.messageType !== "assistant" || markdown.trim() === "") return markdown;
		return `${GUTTER} ${markdown}`;
	});
}

// src/pi.ts
function pi_default(pi) {
	for (const feature of [gutter_default, condense_default]) try {
		feature(pi);
	} catch (error) {
		pi.on("session_start", (_event, ctx) => {
			ctx.ui.notify(`transcript-tweaks failed to load: ${error instanceof Error ? error.message : String(error)}`, "error");
		});
	}
}

