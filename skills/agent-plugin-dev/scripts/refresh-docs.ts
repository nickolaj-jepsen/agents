import { mkdir, writeFile } from "node:fs/promises";

const piTag = process.argv[2] ?? "v1.5.2";
if (!/^v\d+\.\d+\.\d+$/.test(piTag) || process.argv.length > 3) {
  throw new Error("Usage: just plugin-docs [vMAJOR.MINOR.PATCH]");
}

const claude = "https://code.claude.com/docs/en/plugins/";
const pi = `https://raw.githubusercontent.com/earendil-works/pi/${piTag}/`;
const claudePages = [
  "create",
  "components",
  "manifest-reference",
  "mods/create",
  "mods/reference",
  "mods/interface",
  "mods/events",
  "mods/api",
  "mods/test",
  "mods/troubleshoot",
];
const piPages = ["extensions", "packages", "tui"];
const pages = [
  ...claudePages.map((path) => ({
    file: `claude/${path.replace("mods/", "mods-")}.md`,
    source: `${claude}${path}.md`,
  })),
  ...piPages.map((name) => ({
    file: `pi/${name}.md`,
    source: `${pi}packages/coding-agent/docs/${name}.md`,
  })),
];
const local = new Map(pages.map(({ file, source }) => [source, file]));

async function download(source: string) {
  const response = await fetch(source, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`${source}: HTTP ${response.status}`);
  return (await response.text()).replaceAll("\r\n", "\n").trimEnd();
}

function render(body: string, file: string, source: string) {
  if (!/^# \S/m.test(body) || /^\s*<(?:!DOCTYPE|html)\b/i.test(body)) {
    throw new Error(`${source}: expected a Markdown document`);
  }
  let fence = "";
  const lines = body.split("\n").map((line) => {
    const marker = /^ {0,3}(`{3,}|~{3,})/.exec(line)?.[1];
    if (fence) {
      if (marker?.startsWith(fence) && line.trim() === marker) fence = "";
      return line;
    }
    if (marker) {
      fence = marker;
      return line;
    }
    // Keep links between bundled pages local. Resolve other relative links upstream.
    return line.replace(/\]\(([^\s()]+)(?=[\s)])/g, (match, target: string) => {
      if (target.startsWith("#") || (/^[\w+.-]+:/.test(target) && !target.startsWith("https://")))
        return match;
      const url = new URL(target, source);
      const linked = local.get(`${url.origin}${url.pathname}`);
      if (linked && linked.split("/")[0] === file.split("/")[0]) {
        return `](${linked.split("/")[1]}${url.search}${url.hash}`;
      }
      return `](${url.href}`;
    });
  });
  return `<!-- Generated by just plugin-docs. Do not edit. -->\n\nSource: <${source}>\n\n${lines.join("\n")}\n`;
}

// Fetch and validate everything before replacing any existing reference.
const files = await Promise.all([
  ...pages.map(async ({ file, source }) => ({
    file,
    text: render(await download(source), file, source),
  })),
  download(`${pi}LICENSE`).then((text) => ({ file: "pi/LICENSE", text: `${text}\n` })),
]);
const output = new URL("../references/upstream/", import.meta.url);
await Promise.all(
  ["claude/", "pi/"].map((dir) => mkdir(new URL(dir, output), { recursive: true })),
);
for (const { file, text } of files) await writeFile(new URL(file, output), text);
console.log(`Refreshed ${pages.length} Markdown references (Pi ${piTag}).`);
